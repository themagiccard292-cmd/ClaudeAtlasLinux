import { app } from 'electron';
import { autoUpdater, type ProgressInfo, type UpdateInfo } from 'electron-updater';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { AtlasEvent } from '../shared/ipc';
import type { Settings, UpdateState } from '../shared/types';
import { isNewer, reduceUpdate, type UpdateEvent } from './updateState';

const FIRST_CHECK_MS = Number(process.env.ATLAS_UPDATE_DELAY_MS ?? 20_000);
const INTERVAL_MS = 6 * 60 * 60 * 1000;

export interface UpdaterDeps {
  settings: () => Settings;
  emit: (e: AtlasEvent) => void;
  log: (line: string) => void;
}

function installMethod(): 'appimage' | 'deb' | 'unknown' {
  if (process.env.APPIMAGE) return 'appimage';
  try {
    const f = join(process.resourcesPath, 'package-type');
    if (existsSync(f) && readFileSync(f, 'utf8').trim() === 'deb') return 'deb';
  } catch {
    /* not a packaged install */
  }
  return 'unknown';
}

/**
 * Auto-update on top of electron-updater (GitHub Releases feed generated by electron-builder).
 *   AppImage → downloads the new AppImage and swaps the file in place.
 *   .deb     → downloads the .deb and installs it with `dpkg -i` through a graphical password prompt (polkit).
 * Policy: checking and downloading are automatic (configurable); INSTALLING always waits for the user, and
 * never happens while a task is running. Integrity relies on HTTPS + the sha512 in latest-linux.yml.
 */
export class UpdateManager {
  private state: UpdateState;
  private timer: NodeJS.Timeout | null = null;
  private first: NodeJS.Timeout | null = null;
  private busy = false;
  private readonly method = installMethod();
  private readonly override = process.env.ATLAS_UPDATE_URL;
  readonly enabled: boolean;

  constructor(private readonly d: UpdaterDeps) {
    let reason: string | undefined;
    if (!app.isPackaged && !this.override) reason = 'Updates run only in the installed app (AppImage or .deb).';
    else if (this.method === 'unknown' && !this.override) reason = 'This install type cannot update itself — use the AppImage or the .deb.';
    this.enabled = !reason;
    this.state = { status: reason ? 'disabled' : 'idle', currentVersion: app.getVersion(), method: this.method, reason };
  }

  get(): UpdateState {
    return this.state;
  }

  private apply(ev: UpdateEvent): void {
    this.state = reduceUpdate(this.state, ev);
    this.d.emit({ type: 'update', state: this.state });
  }

  start(): void {
    if (!this.enabled) {
      this.d.log(`updater disabled: ${this.state.reason}`);
      return;
    }
    const logger = {
      info: (m: unknown) => this.d.log(`[updater] ${String(m)}`),
      warn: (m: unknown) => this.d.log(`[updater:warn] ${String(m)}`),
      error: (m: unknown) => this.d.log(`[updater:error] ${String(m)}`),
      debug: () => undefined,
    };
    autoUpdater.logger = logger;
    autoUpdater.autoDownload = false; // we decide (settings), so "available" is always visible first
    // AppImage can swap itself silently at the next quit; a .deb would pop a password dialog then, so only on click.
    autoUpdater.autoInstallOnAppQuit = this.method === 'appimage';
    autoUpdater.allowDowngrade = false;
    this.applySettings(this.d.settings());
    if (this.override) autoUpdater.setFeedURL({ provider: 'generic', url: this.override });

    autoUpdater.on('checking-for-update', () => this.apply({ type: 'checking' }));
    autoUpdater.on('update-available', (info: UpdateInfo) => {
      if (!isNewer(info.version, app.getVersion())) return this.apply({ type: 'none' });
      this.apply({ type: 'available', version: info.version, notes: info.releaseNotes });
      if (this.d.settings().updates.autoDownload) void this.download();
    });
    autoUpdater.on('update-not-available', () => this.apply({ type: 'none' }));
    autoUpdater.on('download-progress', (p: ProgressInfo) => this.apply({ type: 'progress', percent: p.percent, bytesPerSecond: p.bytesPerSecond }));
    autoUpdater.on('update-downloaded', (info: UpdateInfo) => this.apply({ type: 'downloaded', version: info.version, notes: info.releaseNotes }));
    autoUpdater.on('error', (err: Error) => this.apply({ type: 'error', message: err?.message?.split('\n')[0] ?? String(err) }));

    this.schedule();
  }

  /** Re-read settings (channel, on/off). */
  applySettings(s: Settings): void {
    if (!this.enabled) return;
    autoUpdater.allowPrerelease = s.updates.channel === 'beta';
    this.schedule();
  }

  private schedule(): void {
    if (this.first) clearTimeout(this.first);
    if (this.timer) clearInterval(this.timer);
    this.first = this.timer = null;
    if (!this.d.settings().updates.check) return;
    this.first = setTimeout(() => void this.check(false), FIRST_CHECK_MS);
    this.timer = setInterval(() => void this.check(false), INTERVAL_MS);
  }

  async check(manual: boolean): Promise<UpdateState> {
    if (!this.enabled || this.busy) return this.state;
    this.busy = true;
    try {
      await autoUpdater.checkForUpdates();
    } catch (e) {
      // `error` event already updated the state; a silent background check must not nag
      if (manual) this.apply({ type: 'error', message: e instanceof Error ? e.message.split('\n')[0] : String(e) });
    } finally {
      this.busy = false;
    }
    return this.state;
  }

  async download(): Promise<UpdateState> {
    if (!this.enabled || (this.state.status !== 'available' && this.state.status !== 'error')) return this.state;
    try {
      this.apply({ type: 'progress', percent: 0, bytesPerSecond: 0 });
      await autoUpdater.downloadUpdate();
    } catch (e) {
      this.apply({ type: 'error', message: e instanceof Error ? e.message.split('\n')[0] : String(e) });
    }
    return this.state;
  }

  /** Call only after the app has released everything (sidecar stopped, lock released). */
  quitAndInstall(): UpdateState {
    autoUpdater.quitAndInstall(false, true); // sync: on failure the `error` event fires before returning
    return this.state;
  }

  dispose(): void {
    if (this.first) clearTimeout(this.first);
    if (this.timer) clearInterval(this.timer);
  }
}
